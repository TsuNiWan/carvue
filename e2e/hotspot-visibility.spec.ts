import { expect, test } from '@playwright/test'
import { openVehicle, presentation } from './helpers'

for (const preference of ['no-preference', 'reduce'] as const) {
  test(`${preference} 拖曳及視角移動隱藏熱點，停止後恢復`, async ({ page }) => {
    await page.emulateMedia({ reducedMotion: preference })
    await openVehicle(page)
    const hotspots = page.locator('[data-hotspot]')
    await expect.poll(() => hotspots.count()).toBeGreaterThan(0)
    const canvas = page.getByLabel('車輛 3D 場景', { exact: true })
    const box = (await canvas.boundingBox())!
    await page.mouse.move(box.x + box.width * 0.5, box.y + box.height * 0.65)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width * 0.58, box.y + box.height * 0.65, { steps: 12 })
    await expect(hotspots).toHaveCount(0)
    await expect(page.getByRole('button', { name: '左前門', exact: true })).toBeEnabled()
    await page.mouse.up()
    await expect.poll(() => hotspots.count()).toBeGreaterThan(0)
    await page.getByRole('button', { name: '前方', exact: true }).click()
    if (preference === 'no-preference') await expect(hotspots).toHaveCount(0)
    await expect.poll(() => hotspots.count()).toBeGreaterThan(0)
    await page.mouse.move(box.x + box.width * 0.5, box.y + box.height * 0.65)
    await page.mouse.wheel(0, 180)
    await expect(hotspots).toHaveCount(0)
    await expect.poll(() => hotspots.count()).toBeGreaterThan(0)
    await page.getByRole('button', { name: '自由', exact: true }).click()
    await expect.poll(() => hotspots.count()).toBeGreaterThan(0)
    await expect(page.getByRole('button', { name: '車輛照明熱點', exact: true })).toBeVisible()
  })

  test(`${preference} 只隱藏活動車門熱點並保留面板反向及焦點`, async ({ page }) => {
    await page.emulateMedia({ reducedMotion: preference })
    await openVehicle(page)
    const door = page.getByRole('button', { name: '左前門熱點', exact: true })
    await expect(door).toBeVisible()
    await door.focus()
    await door.press('Enter')
    await expect(door).toHaveCount(0)
    await expect(page.getByLabel('車輛 3D 場景', { exact: true })).toBeFocused()
    await expect(page.getByRole('button', { name: '車輛照明熱點', exact: true })).toBeVisible()
    await expect.poll(async () => (await presentation(page)).parts.frontLeft).toBeGreaterThan(0.1)
    await page.getByRole('button', { name: '左前門', exact: true }).click()
    await expect.poll(async () => (await presentation(page)).parts.frontLeft).toBe(0)
    await expect(door).toBeVisible()
    const animation = await door.evaluate(element => getComputedStyle(element).animationName)
    expect(animation === 'none').toBe(preference === 'reduce')
    await page.getByRole('button', { name: '後方', exact: true }).click()
    const trunk = page.locator('[data-hotspot="trunk"]')
    await expect(trunk).toBeVisible()
    await page.getByRole('switch', { name: '後車廂', exact: true }).click()
    await expect(trunk).toHaveCount(0)
    await expect.poll(async () => (await presentation(page)).parts.trunk).toBeGreaterThan(0.1)
    await page.getByRole('switch', { name: '後車廂', exact: true }).click()
    await expect.poll(async () => (await presentation(page)).parts.trunk).toBe(0)
    await expect(trunk).toBeVisible()
  })
}
